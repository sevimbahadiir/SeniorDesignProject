"""
step4_llm_verbalization.py
--------------------------
XAI Adım 4: LLM Verbalization

Rule-based engine (Adım 3) çıktısını Anthropic API ile
doğal dile çevirir.

Mimari:
    Diagnosis Engine → JSON → LLM → Human-readable açıklama

LLM karar vermiyor — sadece deterministik sonucu açıklıyor.
Bu hallucination riskini minimuma indirir.

Çıktı:
    xai_llm_explanations.json   → servis bazlı açıklamalar
    xai_llm_report.txt          → okunabilir rapor
"""

import json
import requests

# ─── Diagnosis raporunu yükle ─────────────────────────────────────────────────

with open('xai_diagnosis_report.json', 'r', encoding='utf-8') as f:
    diagnosis_report = json.load(f)

DIAG_TR = {
    'pod_insensitive_bottleneck': 'Pod-Insensitive Bottleneck',
    'marl_optimized':             'MARL Optimized',
    'reward_excluded':            'Reward Excluded (Option C)',
    'under_provisioned':          'Under-Provisioned',
    'over_provisioned':           'Over-Provisioned',
    'healthy':                    'Healthy',
    'monitoring_required':        'Monitoring Required',
}

print("=" * 65)
print("XAI Adım 4: LLM Verbalization")
print("=" * 65)
print("\n  Anthropic API ile servis bazlı açıklama üretiliyor...\n")

# ─── LLM Verbalization Fonksiyonu ────────────────────────────────────────────

def verbalize_service(svc, report):
    """
    Tek bir servis için diagnosis raporunu LLM'e gönder.
    LLM sadece açıklıyor — karar vermiyor.
    """
    d          = report['details']
    diagnosis  = DIAG_TR.get(report['diagnosis'], report['diagnosis'])
    severity   = report['severity']
    action     = report['action']
    confidence = report['confidence']
    evidence   = report['evidence']
    lat_ms     = d['latency_ms']
    p50_ms     = d['p50_ms']
    lat_ratio  = d['latency_ratio']
    pct_impr   = d.get('pct_improvement', 0)
    ippo_lat   = d.get('ippo_lat_ms', lat_ms)
    rb_lat     = d.get('rb_lat_ms', lat_ms)
    in_reward  = d.get('in_reward', True)

    # Sistem prompt: LLM'in rolünü netleştir
    system_prompt = """You are an expert microservice observability analyst.
Your task is to explain pre-computed diagnostic results in clear, 
concise technical language suitable for an academic paper.

Rules:
- Do NOT make up new diagnoses — only explain the given diagnosis
- Be factual and precise
- Use 3-5 sentences maximum
- Mention specific numbers from the evidence
- End with a one-sentence recommendation"""

    # Kullanıcı prompt: diagnosis bilgilerini ver
    user_prompt = f"""Explain the following pre-computed diagnosis for the '{svc}' microservice:

Diagnosis: {diagnosis}
Severity: {severity}
MARL Agent Action: {action} (confidence: {confidence:.2f})
Current Latency: {lat_ms:.0f}ms (p50 threshold: {p50_ms:.0f}ms, ratio: {lat_ratio:.2f}x)
MARL Improvement vs Rule-based: {rb_lat:.0f}ms → {ippo_lat:.0f}ms ({pct_impr:+.1f}%)
In Reward Function: {in_reward}

Evidence from rule-based engine:
{chr(10).join(f"- {ev}" for ev in evidence)}

Write a 3-5 sentence technical explanation of this diagnosis."""

    response = requests.post(
        "https://api.anthropic.com/v1/messages",
        headers={"Content-Type": "application/json"},
        json={
            "model":      "claude-sonnet-4-20250514",
            "max_tokens": 1000,
            "system":     system_prompt,
            "messages":   [{"role": "user", "content": user_prompt}]
        }
    )

    data = response.json()
    text = ""
    for block in data.get("content", []):
        if block.get("type") == "text":
            text += block["text"]
    return text.strip()

# ─── Tüm servisler için çalıştır ─────────────────────────────────────────────

explanations = {}

for svc, report in diagnosis_report.items():
    print(f"  [{svc}] açıklanıyor...", end='', flush=True)
    explanation = verbalize_service(svc, report)
    explanations[svc] = {
        'diagnosis':   DIAG_TR.get(report['diagnosis'], report['diagnosis']),
        'severity':    report['severity'],
        'explanation': explanation,
    }
    print(" ✓")
    print(f"    {explanation[:120]}...")

# ─── Kaydet ───────────────────────────────────────────────────────────────────

with open('xai_llm_explanations.json', 'w', encoding='utf-8') as f:
    json.dump(explanations, f, indent=2, ensure_ascii=False)

# Okunabilir rapor
SEV_ICON = {'critical': '🔴', 'warning': '🟡', 'ok': '🟢', 'info': '🔵'}

report_lines = [
    "=" * 70,
    "XAI SYSTEM REPORT — IPPO Policy Analysis",
    "Robot Shop Microservice Autoscaling",
    "=" * 70,
    "",
]

for svc, data in explanations.items():
    icon = SEV_ICON.get(data['severity'], '⚪')
    report_lines += [
        f"{icon} {svc.upper()} — {data['diagnosis']}",
        "-" * 50,
        data['explanation'],
        "",
    ]

report_lines += [
    "=" * 70,
    "Generated by: Rule-based Diagnosis Engine + LLM Verbalization",
    "Note: Diagnoses are deterministic; LLM provides natural language explanation only.",
    "=" * 70,
]

report_text = "\n".join(report_lines)
with open('xai_llm_report.txt', 'w', encoding='utf-8') as f:
    f.write(report_text)

print(f"\n  ✓ xai_llm_explanations.json")
print(f"  ✓ xai_llm_report.txt")

# ─── Konsol özet ─────────────────────────────────────────────────────────────

print(f"\n{'=' * 65}")
print("LLM AÇIKLAMALARI")
print("=" * 65)
for svc, data in explanations.items():
    icon = SEV_ICON.get(data['severity'], '⚪')
    print(f"\n{icon} {svc.upper()} — {data['diagnosis']}")
    print(f"  {data['explanation']}")

print(f"\n{'=' * 65}")
print("Adım 4 tamamlandı.")
print("=" * 65)
